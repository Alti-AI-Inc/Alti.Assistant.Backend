/**
 * Heuristically corrects typical LLM JSON structural syntax errors.
 * This function attempts to repair common malformations in JSON strings generated by LLMs,
 * such as unescaped newlines, single quotes, unquoted keys, and trailing commas,
 * to make them valid JSON. It also tries to close unclosed brackets/braces.
 *
 * @param {string} rawJson - Raw, potentially malformed JSON string payload from an LLM.
 * @returns {string} A repaired and sanitized JSON string. Returns an empty string if input is null or empty.
 */
const fixA2uiPayload = (rawJson) => {
  if (!rawJson) return '';
  logger.info('GCP A2UI PayloadFixer: Attempting programmatic syntax correction on JSON string...');

  let fixed = rawJson.trim();

  // 1. Repair unescaped newlines inside string literals
  fixed = fixed.replace(/"([^"]*)"/g, (match, group) => {
    return '"' + group.replace(/\n/g, '\\n').replace(/\r/g, '\\r') + '"';
  });

  // 2. Repair single quotes to double quotes for properties and values
  fixed = fixed.replace(/'([^']*)'\s*:/g, '"$1":');
  fixed = fixed.replace(/:\s*'([^']*)'/g, ': "$1"');

  // 3. Repair unquoted property keys
  fixed = fixed.replace(/([{,]\s*)([a-zA-Z0-9_\-]+)\s*:/g, '$1"$2":');

  // 4. Remove trailing commas in objects and arrays
  fixed = fixed.replace(/,\s*([}\]])/g, '$1');

  // 5. Match and close any unclosed trailing brackets/braces using stack matching
  const stack = [];
  let inString = false;
  let escape = false;

  for (let i = 0; i < fixed.length; i++) {
    const char = fixed[i];
    if (escape) {
      escape = false;
      continue;
    }
    if (char === '\\') {
      escape = true;
      continue;
    }
    if (char === '"') {
      inString = !inString;
      continue;
    }
    if (!inString) {
      if (char === '{' || char === '[') {
        stack.push(char === '{' ? '}' : ']');
      } else if (char === '}' || char === ']') {
        if (stack.length > 0 && stack[stack.length - 1] === char) {
          stack.pop();
        }
      }
    }
  }

  while (stack.length > 0) {
    const closeChar = stack.pop();
    fixed += closeChar;
  }

  return fixed;
};

