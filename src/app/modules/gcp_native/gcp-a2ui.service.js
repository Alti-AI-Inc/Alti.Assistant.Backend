/**
 * @typedef {object} A2uiStreamPartPartial
 * @property {'a2ui_partial'} type - Indicates an A2UI payload is currently being buffered but is incomplete.
 * @property {number} bufferedLength - The current length of the buffered A2UI content.
 */

/**
 * @typedef {object} A2uiStreamPartComplete
 * @property {'a2ui_complete'} type - Indicates a complete A2UI payload has been extracted.
 * @property {boolean} success - True if the A2UI JSON was successfully parsed.
 * @property {object} [payload] - The parsed A2UI JSON object if `success` is true.
 * @property {string} [error] - An error message if JSON parsing failed.
 * @property {string} [rawPayload] - The raw A2UI JSON string before parsing, if an error occurred.
 */

/**
 * @typedef {A2uiStreamPartText | A2uiStreamPartPartial | A2uiStreamPartComplete} A2uiStreamPart
 */

/**
 * Stateful stream parser that progressively processes incoming text chunks
 * to extract Google A2UI dynamic components enclosed in `<a2ui-json>` tags.
 * It handles partial tags across chunks and attempts to fix malformed JSON.
 */
class A2uiStreamParser {
  /**
   * Creates an instance of A2uiStreamParser.
   * @param {object} [catalog=null] - An optional catalog object. Currently not used by the parser logic.
   */
  constructor(catalog = null) {
    /**
     * The internal buffer to accumulate text chunks.
     * @type {string}
     */
    this.buffer = '';
    /**
     * A flag indicating whether the parser is currently inside an `<a2ui-json>` block.
     * @type {boolean}
     */
    this.insideTag = false;
    /**
     * The catalog object passed during construction. Currently not used by the parser logic.
     * @type {object|null}
     */
    this.catalog = catalog;
  }

  /**
   * Processes a single chunk of text from a stream.
   * It identifies and extracts A2UI JSON payloads, handling cases where tags
   * or JSON content span across multiple chunks. It also attempts to repair
   * malformed JSON before parsing.
   *
   * @param {string} chunk - The incoming text chunk to process.
   * @returns {A2uiStreamPart[]} An array of processed parts, which can be plain text,
   *                               a partial A2UI payload, or a complete A2UI payload.
   */
  processChunk(chunk) {
    if (!chunk) return [];

    this.buffer += chunk;
    const parts = [];

    while (this.buffer.length > 0) {
      if (!this.insideTag) {
        const tagIndex = this.buffer.toLowerCase().indexOf('<a2ui-json>');

        if (tagIndex === -1) {
          // No opening tag found, treat entire buffer as text
          parts.push({
            type: 'text',
            content: this.buffer
          });
          this.buffer = ''; // Clear buffer as it's all text
          break;
        } else {
          // Opening tag found
          if (tagIndex > 0) {
            // Push text before the tag
            parts.push({
              type: 'text',
              content: this.buffer.substring(0, tagIndex)
            });
          }
          this.insideTag = true;
          this.buffer = this.buffer.substring(tagIndex + '<a2ui-json>'.length);
        }
      } else {
        const closeIndex = this.buffer.toLowerCase().indexOf('</a2ui-json>');

        if (closeIndex === -1) {
          // Inside tag, but no closing tag yet, buffer more
          parts.push({
            type: 'a2ui_partial',
            bufferedLength: this.buffer.length
          });
          break; // Wait for more chunks
        } else {
          // Closing tag found, extract A2UI JSON
          let rawJson = this.buffer.substring(0, closeIndex).trim();
          this.buffer = this.buffer.substring(closeIndex + '</a2ui-json>'.length);
          this.insideTag = false;

          // Sanitization: Strip accidental markdown code blocks wrapped by the LLM
          rawJson = rawJson.replace(/^```json\s*/i, '').replace(/\s*```$/i, '').trim();
          const repairedJson = fixA2uiPayload(rawJson);

          try {
            const parsedPayload = JSON.parse(repairedJson);
            parts.push({
              type: 'a2ui_complete',
              success: true,
              payload: parsedPayload
            });
          } catch (err) {
            parts.push({
              type: 'a2ui_complete',
              success: false,
              error: err.message,
              rawPayload: rawJson // Keep raw payload for debugging if parsing fails
            });
          }
        }
      }
    }

    return parts;
  }
}

/**
 * @typedef {object} A2uiStreamState
 * @property {string} buffer - The current accumulated buffer from previous chunks.
 * @property {boolean} insideTag - Flag indicating if the parser is currently inside an A2UI tag.
 */

/**
 * @typedef {object} ParseA2uiStreamChunkResult
 * @property {A2uiStreamPart[]} parts - An array of processed parts from the current chunk.
 * @property {A2uiStreamState} newState - The updated state of the parser to be passed to the next call.
 */

/**
 * Stateless wrapper function for `A2uiStreamParser` that processes a single stream chunk,
 * returning response parts and an updated state map. This allows for external state management.
 *
 * @param {string} chunk - The incoming text chunk to process.
 * @param {A2uiStreamState} [state={ buffer: '', insideTag: false }] - The current state of the stream parser.
 * @returns {ParseA2uiStreamChunkResult} An object containing the processed parts and the new state.
 */
const parseA2uiStreamChunk = (chunk, state = { buffer: '', insideTag: false }) => {
  const parser = new A2uiStreamParser();
  parser.buffer = state.buffer || '';
  parser.insideTag = state.insideTag || false;

  const parts = parser.processChunk(chunk);

  return {
    parts,
    newState: {
      buffer: parser.buffer,
      insideTag: parser.insideTag
    }
  };
};

/**
 * @typedef {object} A2uiRpcPayload
 * @property {string} componentId - The ID of the component that triggered the RPC action.
 * @property {string} action - The action performed on the component (e.g., 'click', 'submit').
 * @property {object} [values] - An object containing any associated values from the UI component (e.g., form input values).
 */

/**
 * @typedef {object} A2uiRpcResponseUpdate
 * @property {boolean} success - Indicates if the RPC action was processed successfully.
 * @property {string} actionProcessed - The action that was processed.
 * @property {string} timestamp - ISO 8601 timestamp of when the action was processed.
 * @property {object} surfaceUpdate - An object describing the updated A2UI surface.
 * @property {string} surfaceUpdate.root - The ID of the root component for the updated UI.
 * @property {Array<object>} surfaceUpdate.components - An array of component definitions for the updated UI.
 */

/**
 * Stateful dispatcher that processes incoming user interface actions (RPCs) from an A2UI client.
 * This function simulates running bound tools or logic based on the `rpcPayload` and
 * returns an updated dynamic layout to the client.
 *
 * @param {object} sessionState - The current session state, which might include existing components and their values.
 *                                This parameter is currently not used in the example implementation but is provided for future extensibility.
 * @param {A2uiRpcPayload} rpcPayload - The RPC trigger packet containing details about the user's interaction.
 * @returns {Promise<A2uiRpcResponseUpdate>} A promise that resolves to an interactive response update,
 *                                           describing how the UI should change.
 */
const handleA2uiRpc = async (sessionState, rpcPayload) => {
  logger.info(`GCP A2UI RPC: Executing action "${rpcPayload.action}" on component "${rpcPayload.componentId}"...`);

  const componentId = rpcPayload.componentId || 'unknown';
  const action = rpcPayload.action || 'click';
  const values = rpcPayload.values || {};

  // Construct a standard response update with a refreshed dynamic surface
  const responseUpdate = {
    success: true,
    actionProcessed: action,
    timestamp: new Date().toISOString(),
    surfaceUpdate: {
      root: 'rpc-status-layout',
      components: [
        {
          id: 'rpc-status-layout',
          type: 'column',
          children: ['status-lbl', 'refresh-btn']
        },
        {
          id: 'status-lbl',
          type: 'text',
          content: `Action "${action}" on component "${componentId}" processed successfully! Recipient received values: ${JSON.stringify(values)}`
        },
        {
          id: 'refresh-btn',
          type: 'button',
          label: 'Continue Interactive Exploration',
          action: 'reset_explore'
        }
      ]
    }
  };

  return responseUpdate;
};

/**
 * @typedef {object} ActivateExtensionResult
 * @property {boolean} success - True if the extension was successfully activated.
 * @property {string} activatedId - The ID of the component that was activated.
 * @property {string[]} catalogKeys - An array of all component keys currently in the active catalog, including the newly added one.
 */

/**
 * Dynamically registers and validates a new custom dynamic UI component in the active catalog.
 * This allows for extending the set of components an LLM can generate.
 *
 * @param {string} extensionId - The unique namespace identifier for the extension component (e.g., 'myCustomCard').
 * @param {A2uiComponentSchema} componentSchema - The JSON Schema defining the new component's structure, properties, and required fields.
 * @returns {ActivateExtensionResult} An object indicating the activation result status, including the activated ID and updated catalog keys.
 * @throws {Error} If `extensionId` or `componentSchema` are not provided.
 */
const tryActivateExtension = (extensionId, componentSchema) => {
  logger.info(`GCP A2UI: Attempting to dynamically activate extension component "${extensionId}"...`);

  if (!extensionId || !componentSchema) {
    throw new Error('Extension ID and Component Schema are required.');
  }

  // Merge the new schema into our active basic catalog configuration
  A2UI_BASIC_CATALOG[extensionId] = componentSchema;

  return {
    success: true,
    activatedId: extensionId,
    catalogKeys: Object.keys(A2UI_BASIC_CATALOG)
  };
};

