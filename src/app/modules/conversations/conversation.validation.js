/**
 * @file This file defines Zod schemas for validating various conversation-related API requests.
 * It includes schemas for creating, updating, retrieving, and managing conversations and their messages,
 * as well as schemas for sharing conversations.
 * These schemas are used to ensure that incoming request data conforms to expected structures and types.
 */

import * as zod from 'zod';
const { z } = zod;

const parseQueryNumber = (val) => {
  if (val === undefined || val === null || val === '') return undefined;
  if (typeof val === 'number') return val;
  if (typeof val === 'string') {
    const num = Number(val);
    return isNaN(num) ? val : num;
  }
  return val;
};

const queryPageSchema = z.preprocess(parseQueryNumber, z.number({ invalid_type_error: 'Page must be a number' }).int().positive()).optional();
const queryLimitSchema = z.preprocess(parseQueryNumber, z.number({ invalid_type_error: 'Limit must be a number' }).int().positive()).optional();

const queryDeepSearchSchema = z.preprocess((val) => {
  if (val === undefined || val === null || val === '') return undefined;
  if (val === true || val === 'true') return true;
  if (val === false || val === 'false') return false;
  return 'invalid';
}, z.boolean({ invalid_type_error: 'is_deep_search must be true or false' }).optional());


/**
 * @typedef {object} Message
 * @property {'user'|'assistant'|'system'} role - The role of the message sender.
 * @property {string} content - The actual content of the message.
 * @property {Record<string, any>} [metadata] - Optional metadata associated with the message.
 */
/**
 * Zod schema for validating a single message object within a conversation.
 * Ensures the message has a valid role and non-empty content.
 * @type {z.ZodObject<any, any, any, Message, any>}
 */
const messageSchema = z.object({
  role: z.enum(['user', 'assistant', 'system'], {
    errorMap: (issue, ctx) => {
      if (issue.code === 'invalid_type' && issue.received === 'undefined') {
        return { message: 'Message role is required' };
      }
      return { message: 'Role must be user, assistant, or system' };
    }
  }),
  content: z
    .string({
      required_error: 'Message content is required',
    })
    .min(1, 'Message content cannot be empty')
    // SECURITY PATCH: Add a maximum length to prevent DoS attacks with overly large payloads.
    .max(50000, 'Message content must be less than 50,000 characters'),
  // SECURITY PATCH: Restrict metadata values to primitives to prevent NoSQL injection vulnerabilities
  // where operators (e.g., { "$ne": null }) could be passed in the `any()` type.
  metadata: z
    .record(z.string(), z.union([z.string(), z.number(), z.boolean(), z.null()]))
    .optional(),
});

/**
 * @typedef {object} CreateConversationBody
 * @property {string} [title] - Optional title for the new conversation.
 * @property {Message} [initialMessage] - Optional initial message to start the conversation.
 * @property {object} [metadata] - Optional metadata for the conversation.
 * @property {string} [metadata.model] - The AI model to use for the conversation.
 * @property {number} [metadata.temperature] - The creativity temperature for the AI model (0-2).
 * @property {number} [metadata.maxTokens] - The maximum number of tokens for AI responses.
 * @property {string[]} [metadata.tags] - An array of tags associated with the conversation.
 * @property {string} [metadata.category] - The category of the conversation.
 * @property {Record<string, any>} [metadata.customData] - Custom key-value data for the conversation.
 * @property {boolean} [is_deep_search] - Flag indicating if deep search should be enabled for this conversation.
 */
/**
 * Zod schema for validating the request body when creating a new conversation.
 * It allows for an optional title, initial message, and various metadata fields.
 * @type {z.ZodObject<any, any, any, { body: CreateConversationBody }, any>}
 */
const createConversationSchema = z.object({
  body: z.object({
    title: z
      .string()
      .max(255, 'Title must be less than 255 characters')
      .optional(),
    // BUG FIX: conversationId should not be provided by the client during creation.
    // It should be generated by the backend to prevent IDOR vulnerabilities and
    // ensure proper resource management.
    // conversationId: z
    //   .string({
    //     required_error: 'Conversation ID is required',
    //   })
    //   .min(1, 'Conversation ID cannot be empty'),
    initialMessage: messageSchema.optional(),
    metadata: z
      .object({
        // SECURITY PATCH: Add max length to prevent overly long input.
        model: z.string().max(100, 'Model name must be less than 100 characters').optional(),
        temperature: z.number().min(0).max(2).optional(),
        maxTokens: z.number().positive().optional(),
        // SECURITY PATCH: Add constraints to tags to prevent overly long values or too many tags.
        tags: z.array(z.string().min(1).max(50, 'Tag must be 50 characters or less')).max(20, 'A maximum of 20 tags are allowed').optional(),
        // SECURITY PATCH: Add max length to category string.
        category: z.string().max(100, 'Category must be 100 characters or less').optional(),
        // SECURITY PATCH: Restrict customData values to primitives to prevent NoSQL injection.
        customData: z.record(z.string(), z.union([z.string(), z.number(), z.boolean(), z.null()])).optional(),
      })
      .optional(),
    is_deep_search: z.boolean().optional(),
  }),
});

