/**
 * @openapi
 * /llama4/prompt:
 *   post:
 *     summary: Get a response from the Llama4 AI model
 *     description: >
 *       Submits a user prompt to the Llama4 AI service and returns the generated response.
 *       This endpoint requires user authentication, and the conversation history is maintained
 *       on a per-user, per-session basis.
 *     tags:
 *       - "Llama4 AI - User"
 *     security:
 *       - bearerAuth: []
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required:
 *               - prompt
 *             properties:
 *               prompt:
 *                 type: string
 *                 description: The text prompt to send to the AI model.
 *                 example: "What is the capital of France?"
 *               sessionId:
 *                 type: string
 *                 format: uuid
 *                 description: >
 *                   The unique identifier for a specific conversation session.
 *                   If not provided, a new session may be initiated.
 *                 example: "a1b2c3d4-e5f6-7890-1234-567890abcdef"
 *     responses:
 *       200:
 *         description: OK. The AI response was generated successfully.
 *         content:
 *           application/json:
 *             schema:
 *               type: object
 *               properties:
 *                 success:
 *                   type: boolean
 *                   example: true
 *                 statusCode:
 *                   type: integer
 *                   example: 200
 *                 message:
 *                   type: string
 *                   example: "Response processed successfully."
 *                 data:
 *                   type: object
 *                   description: The data returned from the AI service.
 *                   properties:
 *                     response:
 *                       type: string
 *                       description: The text response generated by the Llama4 model.
 *                       example: "The capital of France is Paris."
 *       400:
 *         description: Bad Request. The request body is missing the required 'prompt' field.
 *       401:
 *         description: Unauthorized. The user is not authenticated.
 *       500:
 *         description: Internal Server Error. An unexpected error occurred on the server.
 */
/**
 * Handles the request to get a response from the Llama4 AI service.
 * It validates the incoming request, extracts the user's prompt and session ID,
 * retrieves the authenticated user's ID, and calls the service layer to process the request.
 *
 * @function Llama4AiGetResponse
 * @async
 * @param {import('express').Request} req - The Express request object. Expects `prompt` and optional `sessionId` in the body, and `user.id` from authentication middleware.
 * @param {import('express').Response} res - The Express response object.
 * @returns {Promise<void>} A promise that resolves when the response has been sent.
 * @description
 *   - **Permissions:** Requires an authenticated user. Any role is permitted.
 *   - **Multi-tenancy:** The user's ID (`req.user.id`) is used to scope the AI interaction, ensuring data isolation between users.
 */
const Llama4AiGetResponse = catchAsync(async (req, res) => {
  // Security Note: The userId is securely sourced from `req.user.id`, which is populated by
  // the authentication middleware. This prevents IDOR vulnerabilities where a user could
  // specify another user's ID in the request body.
  const { prompt, sessionId } = await validatePromptRequest(req);
  const userId = req.user.id; // Securely get userId from the authenticated user's context

  // AI Safety & PII Guard: Mask potential PII from the user prompt before sending it to the AI service.
  const sanitizedPrompt = maskPII(prompt);

  const result = await Llama4AiServices.Llama4AiGetResponseService(
    sanitizedPrompt, // Use the sanitized prompt for the AI service call.
    userId,
    sessionId
  );

  sendResponse(res, {
    statusCode: httpStatus.OK,
    success: true,
    message: 'Response processed successfully.',
    data: result,
  });
});

